package org.example;

public class finance
{
    private int moneyAmount;
    private String personToDeposit;
    private String departmentDeposit;

    public void setMoneyAmount(int moneyAmount)
    {
        this.moneyAmount=moneyAmount;
    }

    public int getMoneyAmount()
    {
        return moneyAmount;
    }

    public void setPersonToDeposit(String personToDeposit)
    {
        this.personToDeposit=personToDeposit;
    }

    public String getPersonToDeposit()
    {
        return personToDeposit;
    }

    public void setDepartmentDeposit(String departmentDeposit)
    {
        this.departmentDeposit=departmentDeposit;
    }

    public String getDepartmentDeposit()
    {
        return departmentDeposit;

    }






}
